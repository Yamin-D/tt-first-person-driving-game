"""Build the single-file src/project.v that Tiny Tapeout and Vulkos use.

The design is developed as one module per file in dev/rtl/ (top module
tt_um_road_racer). This joins them, top module first, and renames the top
module to the `top_module` named in info.yaml, so the file always matches
what the GitHub actions build.

    python3 dev/tools/combine.py           write src/project.v
    python3 dev/tools/combine.py --check   exit 1 if src/project.v is out of date
"""
import os, re, sys

DEV = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
REPO = os.path.join(DEV, "..")
RTL = os.path.join(DEV, "rtl")
OUT = os.path.join(REPO, "src", "project.v")
DEV_TOP = "tt_um_road_racer"
ORDER = ["project.v", "vga_timing.v", "ip_input_sync.v", "car_state.v",
         "line_setup.v", "pixel_colour.v", "engine_audio.v"]

def top_module_from_info():
    text = open(os.path.join(REPO, "info.yaml")).read()
    m = re.search(r'^\s*top_module:\s*"([^"]+)"', text, re.M)
    if not m:
        sys.exit("top_module not found in info.yaml")
    return m.group(1)

def build():
    parts = []
    for name in ORDER:
        text = open(os.path.join(RTL, name)).read().strip()
        text = text.replace("`default_nettype none\n", "")   # added once at the top
        parts.append("// " + "=" * 74 + "\n// " + name + "\n// " + "=" * 74 + "\n" + text)
    out = ("// Generated by dev/tools/combine.py from dev/rtl/. Edit those files, not this one.\n"
           "`default_nettype none\n\n" + "\n\n".join(parts) + "\n")
    top = top_module_from_info()
    assert re.fullmatch(r"tt_um_\w+", top), "top_module must start with tt_um_"
    return out.replace("module " + DEV_TOP, "module " + top), top

if __name__ == "__main__":
    text, top = build()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit("src/project.v is out of date: run python3 dev/tools/combine.py")
        print("src/project.v is up to date")
    else:
        open(OUT, "w").write(text)
        print("wrote src/project.v (%d modules, top module %s)" % (text.count("\nmodule "), top))
